function seoSections(t: Translation): SEOSection[] {
  const extendedParagraphs = [
    `${t.paragraphs[1]} ${t.paragraphs[2]} ${t.before}`,
    `${t.paragraphs[3]} ${t.paragraphs[4]} ${t.diagnostic}`,
    `${t.paragraphs[5]} ${t.tip} ${t.goodDescription}`,
  ];

  return [
    { type: "title", text: t.seoTitle, level: 2 },
    ...[...t.paragraphs, ...extendedParagraphs].map((html) => ({
      type: "paragraph" as const,
      html,
    })),
    {
      type: "stats",
      columns: 3,
      items: [
        { value: "2", label: t.stats[0], icon: "mdi:vector-line" },
        {
          value: "1",
          label: t.stats[1],
          icon: "mdi:calculator-variant-outline",
        },
        {
          value: "±",
          label: t.stats[2],
          icon: "mdi:arrow-expand-horizontal",
        },
      ],
    },
    { type: "title", text: t.formulaTitle, level: 3 },
    { type: "code", code: t.formula, ariaLabel: t.formulaAria },
    {
      type: "card",
      icon: "mdi:ruler-square",
      title: t.beforeTitle,
      html: t.before,
    },
    {
      type: "table",
      headers: t.tableHeaders,
      rows: t.tableRows,
    },
    { type: "title", text: t.goodTitle, level: 3 },
    {
      type: "comparative",
      columns: 2,
      items: [
        {
          title: t.goodTitle,
          description: t.goodDescription,
          points: t.goodPoints,
          highlight: true,
          pointIcon: "mdi:check",
        },
        {
          title: t.stopTitle,
          description: t.stopDescription,
          points: t.stopPoints,
          pointIcon: "mdi:alert-outline",
        },
      ],
    },
    { type: "title", text: t.vocabularyTitle, level: 3 },
    {
      type: "glossary",
      items: t.glossary.map(([term, definition]) => ({ term, definition })),
    },
    { type: "summary", title: t.summaryTitle, items: t.summary },
    {
      type: "diagnostic",
      variant: "warning",
      title: t.diagnosticTitle,
      badge: "LIMIT",
      icon: "mdi:camera-off-outline",
      html: t.diagnostic,
    },
    { type: "tip", title: t.tipTitle, html: t.tip },
  ];
}

function makeContent(
  t: Translation,
): ToolLocaleContent<ForensicEvidenceScaleUI> {
  const faq: FAQItem[] = t.faq.map(([question, answer]) => ({
    question,
    answer,
  }));
  const howTo: HowToStep[] = t.howTo.map(([name, text]) => ({ name, text }));

  return {
    slug: t.slug,
    title: t.title,
    description: t.description,
    ui: t.ui,
    seo: seoSections(t),
    faq,
    bibliography,
    howTo,
    schemas: [
      {
        "@context": "https://schema.org",
        "@type": "SoftwareApplication",
        name: t.title,
        description: t.description,
        applicationCategory: "EducationalApplication",
        operatingSystem: "Any",
      },
      {
        "@context": "https://schema.org",
        "@type": "FAQPage",
        mainEntity: faq.map((item) => ({
          "@type": "Question",
          name: item.question,
          acceptedAnswer: { "@type": "Answer", text: item.answer },
        })),
      },
      {
        "@context": "https://schema.org",
        "@type": "HowTo",
        name: t.title,
        step: howTo.map((step) => ({
          "@type": "HowToStep",
          name: step.name,
          text: step.text,
        })),
      },
    ],
  };
}

interface CompactTranslationSeed {
  slug: string;
  title: string;
  description: string;
  ui: ForensicEvidenceScaleUI;
  seoTitle: string;
  paragraphs: string[];
  faq: [string, string][];
  howTo: [string, string][];
}

function makeCompactTranslation(seed: CompactTranslationSeed): Translation {
  const { ui } = seed;
  const label = (key: keyof ForensicEvidenceScaleUI): string => ui[key] as string;
  const paragraph = (index: number): string => seed.paragraphs[index] as string;
  return {
    ...seed,
    stats: [label("referenceLength"), label("scaleFactor"), label("margin")],
    formulaTitle: label("scaleFactor"),
    formula: "evidence = evidence pixels × (reference size ÷ reference pixels)",
    formulaAria: label("results"),
    beforeTitle: label("controls"),
    before: paragraph(1),
    tableHeaders: [label("controls"), label("referenceLength"), label("results")],
    tableRows: [
      [label("referenceLength"), label("referenceRealSize"), label("scaleFactor")],
      [label("evidenceLength"), label("evidencePixelLength"), label("results")],
      [label("interval"), label("margin"), label("interval")],
    ],
    goodTitle: label("results"),
    goodDescription: paragraph(0),
    goodPoints: [label("referenceLength"), label("samePlane"), label("margin")],
    stopTitle: label("perspectiveWarning"),
    stopDescription: paragraph(4),
    stopPoints: [label("referencePixelLength"), label("evidencePixelLength"), label("uncertaintyPercent")],
    vocabularyTitle: label("controls"),
    glossary: [
      [label("referenceLength"), paragraph(1)],
      [label("evidenceLength"), paragraph(2)],
      [label("scaleFactor"), paragraph(3)],
      [label("interval"), paragraph(4)],
    ],
    summaryTitle: label("traceLabel"),
    summary: [label("referenceRealHelp"), label("pixelHelp"), label("uncertaintyHelp"), label("disclaimer")],
    diagnosticTitle: label("perspectiveWarning"),
    diagnostic: paragraph(4),
    tipTitle: label("traceLabel"),
    tip: paragraph(5),
  };
}

